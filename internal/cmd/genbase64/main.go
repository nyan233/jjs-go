// Command genbase64 extracts the relocatable body of the hand-written ARM64
// Base64 kernel. Go assembly and JIT therefore execute identical instructions.
package main

import (
	"bytes"
	"encoding/binary"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strconv"
)

func main() {
	command := exec.Command("go", "tool", "asm", "-I", filepath.Join(runtime.GOROOT(), "pkg", "include"), "-S", "-o", os.DevNull, "base64_kernel_arm64.s")
	command.Env = append(os.Environ(), "GOARCH=arm64")
	output, err := command.CombinedOutput()
	if err != nil {
		panic(fmt.Sprintf("assembler: %v\n%s", err, output))
	}
	line := regexp.MustCompile(`(?m)^\s*0x([0-9a-f]+) ((?:[0-9a-f]{2} ){1,16})`)
	var code []byte
	for _, match := range line.FindAllSubmatch(output, -1) {
		offset, _ := strconv.ParseInt(string(match[1]), 16, 64)
		if int(offset) != len(code) {
			panic("non-contiguous assembly")
		}
		data, err := hex.DecodeString(string(bytes.ReplaceAll(match[2], []byte(" "), nil)))
		if err != nil {
			panic(err)
		}
		code = append(code, data...)
	}
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by go generate; DO NOT EDIT.\n//go:build arm64 || arm64_asm_test\n\npackage compiler\n\nvar base64Kernel = [...]uint32{")
	found := false
	for i := 16; i+4 <= len(code); i += 4 {
		word := binary.LittleEndian.Uint32(code[i:])
		if word == 0xd65f03c0 {
			found = true
			break
		}
		fmt.Fprintf(&source, "0x%08x,\n", word)
	}
	if !found {
		panic("missing kernel RET")
	}
	fmt.Fprintln(&source, "}")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("jit_base64_words_arm64_impl.go", formatted, 0644); err != nil {
		panic(err)
	}
}
